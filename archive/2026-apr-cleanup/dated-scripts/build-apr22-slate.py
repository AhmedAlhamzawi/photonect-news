def beat_to_props(label, ar_heading, ar_body, big_stat, support, broll, accent):
    return {
        "label": label,
        "arabicHeading": ar_heading,
        "arabicBody": ar_body,
        "bigStat": {
            "value": big_stat["value"],
            "label": big_stat["label"],
            "arabicLabel": big_stat["ar_label"],
        },
        "supportingStats": [{"label": s["label"], "value": s["value"]} for s in support],
        "broll": broll,
        "brollType": "image",
        "accent": accent,
    }


def entry_to_props(e: dict) -> dict:
    slug = e["slug"]
    broll_paths = [f"images/news/{slug}/broll_{i+1}.jpg" for i in range(3)]
    hero_path = f"images/news/{slug}/hero.jpg"

    beats_props = []
    for i, b in enumerate(e["beats"]):
        beats_props.append(beat_to_props(
            b["label"], b["ar_heading"], b["ar_body"],
            b["big_stat"], b["support"], broll_paths[i], e["accent"],
        ))

    return {
        "dateLabel": DATE_LABEL,
        "arabicDateLabel": ARABIC_DATE_LABEL,
        "handle": "@photonect.news",
        "topicBucket": e["bucket"],
        "variant": e["variant"],
        "audioBed": e["audio_bed"],
        "breaking": {
            "arabicKicker": e["breaking"]["ar_kicker"],
            "arabicHeadline": e["breaking"]["ar_headline"],
            "englishSubhead": e["breaking"]["en_subhead"],
            "heroQueries": e["breaking"]["queries"],
            "heroMedia": hero_path,
            "heroMediaType": "image",
        },
        "beats": beats_props,
        "sources": [{"name": n, "domain": d} for n, d in e["sources"]],
        "arabicTicker": e["ticker"],
    }


def validate_slate():
    """Pre-flight checks: unique beds, adjacency, 12 entries."""
    errs = []
    if len(SLATE) != 12:
        errs.append(f"slate has {len(SLATE)} entries, expected 12")
    beds = [e["audio_bed"] for e in SLATE]
    if len(set(beds)) != 12:
        from collections import Counter
        dups = [b for b, c in Counter(beds).items() if c > 1]
        errs.append(f"duplicate audio beds: {dups}")
    for i in range(len(SLATE) - 1):
        if SLATE[i]["bucket"] == SLATE[i + 1]["bucket"]:
            errs.append(f"adjacency collision: slot {i+1} and {i+2} both '{SLATE[i]['bucket']}'")
    # Body length: should be 20-35 words per body (roughly)
    for e in SLATE:
        for bi, b in enumerate(e["beats"]):
            wc = len(b["ar_body"].split())
            if wc < 18 or wc > 38:
                errs.append(f"{e['slug']} beat{bi+1} body word count={wc} outside 18-38")
    # Tickers
    for e in SLATE:
        if len(e["ticker"]) != 7:
            errs.append(f"{e['slug']} ticker has {len(e['ticker'])} items, expected 7")
    return errs


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dry", action="store_true", help="validate only; write nothing")
    args = ap.parse_args()

    errs = validate_slate()
    if errs:
        print("❌ SLATE VALIDATION FAILED")
        for e in errs:
            print(f"  · {e}")
        sys.exit(2)

    print(f"✓ slate validates — {len(SLATE)} slots, 12 unique beds, zero adjacency collisions")
    print(f"  buckets: {sorted(set(e['bucket'] for e in SLATE))}")
    print(f"  variants: {sorted(set(e['variant'] for e in SLATE))}")
    print("")
    print("plan:")
    for e in SLATE:
        bed = e["audio_bed"].split("/")[-1]
        print(f"  {e['time']}  {e['slug']:38s}  {e['bucket']:18s} {e['variant']}  {bed}")

    if args.dry:
        print("\n(dry — exiting without writing)")
        return

    print("")
    print("writing 12 props.json...")
    for e in SLATE:
        slug = e["slug"]
        d = POSTS / slug
        d.mkdir(parents=True, exist_ok=True)
        p = entry_to_props(e)
        (d / "props.json").write_text(
            json.dumps(p, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        print(f"  ✓ {slug}/props.json")

    print("")
    print(f"✓ wrote {len(SLATE)} props files under {POSTS}")


if __name__ == "__main__":
    main()

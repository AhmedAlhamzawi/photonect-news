def build(slug, d):
    hero_slot = d.get("hero", "hero.jpg")
    return {
        "dateLabel": DATE_LABEL,
        "arabicDateLabel": AR_DATE,
        "handle": "@photonect.news",
        "audioBed": "audio/mood_newsroom.mp3",
        "topicBucket": d["topicBucket"],
        "variant": d["variant"],
        "breaking": {
            "arabicKicker": d["kicker"],
            "arabicHeadline": d["headline"],
            "englishSubhead": d["subhead"],
            "heroMedia": img(slug, hero_slot),
            "heroMediaType": "image",
        },
        "beats": d["beats"],
        "sources": d["sources"],
        "arabicTicker": d["ticker"],
    }


def main():
    for slug, d in SLATE.items():
        full = f"{DATE}-{slug}"
        meta = POSTS / full / ".meta"
        meta.mkdir(parents=True, exist_ok=True)
        props = build(slug, d)
        (meta / "props.json").write_text(json.dumps(props, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"  ✓ {full}  ({len(props['beats'])} beats, variant {d['variant']}, {d['topicBucket']})")
    print(f"\n{len(SLATE)} props written for {DATE}")


if __name__ == "__main__":
    main()

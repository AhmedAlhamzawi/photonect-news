def build():
    for slug, s in SLUGS.items():
        full = f"{D}-{slug}"
        d = POSTS / full
        (d / ".meta").mkdir(parents=True, exist_ok=True)
        props = {
            "dateLabel": DATE_LABEL,
            "arabicDateLabel": AR_DATE,
            "handle": "@photonect.news",
            "audioBed": "audio/music_01.mp3",
            "topicBucket": s["bucket"],
            "variant": s["variant"],
            "breaking": {
                "arabicKicker": s["kicker"],
                "arabicHeadline": s["headline"],
                "englishSubhead": s["subhead"],
                "heroMedia": img(slug, s["hero"]),
                "heroMediaType": "image",
            },
            "beats": s["beats"],
            "sources": [{"name": n, "domain": dm} for n, dm in s["sources"]],
            "arabicTicker": s["ticker"],
        }
        (d / ".meta" / "props.json").write_text(json.dumps(props, ensure_ascii=False, indent=2))

        c = s["caption"]
        caption = (
            f"{c['hook']}\n\n"
            f"{c['teaser']}\n\n"
            f"{c['question']}\n\n"
            f"{c['sources']}\n"
            f"{' '.join(c['tags'])}\n"
            f"@photonect.news"
        )
        (d / "caption.txt").write_text(caption)

        if "v11" in s:
            v = s["v11"]
            brief = {
                "slug": full,
                "kicker": "عاجل",
                "hookHeadline": v["hook"],
                "voText": v["vo"],
                "endQuestion": v["endq"],
                "sourcesLine": v["sources"],
                "images": [img(slug, "hero.jpg"), img(slug, "broll_1.jpg"),
                           img(slug, "broll_2.jpg"), img(slug, "broll_3.jpg")],
                "audioBed": "audio/mood_newsroom.mp3",
                "statPops": [{"value": val, "label": lab, "matchWord": mw} for val, lab, mw in v["pops"]],
            }
            (d / ".meta" / "v11-brief.json").write_text(json.dumps(brief, ensure_ascii=False, indent=2))
        print(f"  ✓ {full}  ({'V11' if 'v11' in s else 'V10 control'})")


if __name__ == "__main__":
    build()
